#!/usr/bin/env python3
"""Build optional exact-coordinate temporal native bundles without changing production.
A pack contains the UNION of source records active anywhere in its closed date range.
Runtime must retain selected-year active records; no geometry/date interpolation occurs.
"""
import argparse,gzip,hashlib,json,pathlib,time

def read(p):
 b=p.read_bytes();return json.loads(gzip.decompress(b) if b[:2]==b'\x1f\x8b' else b)
def encode(v):return json.dumps(v,ensure_ascii=False,sort_keys=True,separators=(',',':'),allow_nan=False).encode()
def sha(b):return hashlib.sha256(b).hexdigest()
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--root',type=pathlib.Path,required=True);ap.add_argument('--output',type=pathlib.Path,required=True);ap.add_argument('--target-kib',type=int,default=256);args=ap.parse_args()
 root=args.root.resolve();out=args.output.resolve()
 assert root not in out.parents and out!=root,'Output must be outside project';out.mkdir(parents=True,exist_ok=True)
 folder=root/'public/data/native';index=read(folder/'index.json.gz');cat=read(root/'public/data/fast/catalog.json.gz');manifest=read(folder/'manifest.json')
 records=[r for r in cat['records'] if r['type']=='POLITY'];byid={r['id']:r for r in records};sizes={s['file']:s['gzipBytes'] for s in manifest['shards']};weight={gid:sizes[file] for gid,file in index['geometryIndex'].items()}
 changes=sorted({r['start'] for r in records}|{r['end']+1 for r in records}); intervals=[]
 for a,b in zip(changes,changes[1:]):
  active={r['id'] for r in records if r['start']<=a<=r['end']};intervals.append((a,b-1,active))
 groups=[]; current=None
 for a,b,active in intervals:
  ids=active if current is None else current[2]|active
  gids={index['recordIndex'][id] for id in ids};estimate=sum(weight[gid] for gid in gids)
  if current and estimate>args.target_kib*1024:
   groups.append(current);current=(a,b,active)
  elif current:current=(current[0],b,ids)
  else:current=(a,b,active)
 if current:groups.append(current)
 geometries={};assets=[];t0=time.perf_counter()
 for i,(start,end,ids) in enumerate(groups):
  mapping={id:index['recordIndex'][id] for id in sorted(ids)};gids=sorted(set(mapping.values()))
  for gid in gids:
   if gid not in geometries:geometries[gid]=read(folder/index['geometryIndex'][gid])[gid]
  pack={'version':1,'start':start,'end':end,'recordIndex':mapping,'geometries':{gid:geometries[gid] for gid in gids}}
  b=encode(pack);gz=gzip.compress(b,compresslevel=9,mtime=0);file=f'temporal/pack-{i:03d}.json.gz';path=out/file;path.parent.mkdir(exist_ok=True);path.write_bytes(gz)
  assert read(path)==pack
  for id,gid in mapping.items():
   assert pack['geometries'][gid]==geometries[index['recordIndex'][id]]
   assert byid[id]['start']<=end and byid[id]['end']>=start
  assets.append({'file':file,'start':start,'end':end,'records':len(ids),'geometries':len(gids),'bytes':len(b),'gzipBytes':len(gz),'gzipSha256':sha(gz)})
 # Every source POLITY record must appear in every pack whose period overlaps it.
 checked=0
 for a,b,active in intervals:
  p=next(p for p in assets if p['start']<=a<=p['end']);data=read(out/p['file']);assert active<=data['recordIndex'].keys();checked+=len(active)
 newindex=dict(index);newindex['temporalBundles']={str(p['start']):{'end':p['end'],'file':p['file']} for p in assets};idx=encode(newindex);idxgz=gzip.compress(idx,compresslevel=9,mtime=0);(out/'index.json.gz').write_bytes(idxgz)
 lookup=[[p['start'],p['end'],p['file']] for p in assets]
 (out/'native-temporal-index.js').write_text('// Generated by scripts/build-temporal-native.py; verified against the source index at release.\nexport const nativeTemporalBundles='+encode(lookup).decode()+';\n')
 sample=[]
 for year in [1450,1500,1510,1666,1800,1850,1900,1915,1940,1968,2000,2024]:
  active=[r for r in records if r['start']<=year<=r['end']];files={index['geometryIndex'][index['recordIndex'][r['id']]] for r in active};p=next(p for p in assets if p['start']<=year<=p['end']);oldbytes=sum(sizes[f] for f in files)
  sample.append({'year':year,'records':len(active),'oldRequestsExcludingIndex':len(files),'oldBytesExcludingIndex':oldbytes,'bundleRequestsExcludingIndex':1,'bundleBytesExcludingIndex':p['gzipBytes'],'bundleStart':p['start'],'bundleEnd':p['end']})
 report={'kind':'pure-data build / exact value and chronological inclusion verification; not browser speed measurement','projectRoot':str(root),'targetCompressedIndividualWeightKiB':args.target_kib,'sourceIndexSHA256':sha((folder/'index.json.gz').read_bytes()),'sourceCatalogSHA256':sha((root/'public/data/fast/catalog.json.gz').read_bytes()),'sourcePolityRecords':len(records),'sourceChangeIntervals':len(intervals),'packs':len(assets),'packBytes':sum(p['gzipBytes'] for p in assets),'maxPackBytes':max(p['gzipBytes'] for p in assets),'oldIndexBytes':(folder/'index.json.gz').stat().st_size,'newIndexBytes':len(idxgz),'verifiedActiveRecordIntervalPairs':checked,'elapsedSeconds':round(time.perf_counter()-t0,3),'sample':sample,'assets':assets}
 (out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items() if k!='assets'},indent=2))
if __name__=='__main__':main()
