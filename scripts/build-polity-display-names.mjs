import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const input=JSON.parse(fs.readFileSync(path.join(root,'editorial/polity-display-names.json'),'utf8'));
const read=p=>JSON.parse(gunzipSync(fs.readFileSync(path.join(root,p))));
const catalogs=['public/data/catalog.json.gz','public/data/fast/catalog.json.gz'].map(p=>new Map(read(p).records.map(r=>[r.id,r])));
assert.equal(input.schemaVersion,1);const seen=new Set(),sourceIds=new Set(input.sources.map(s=>s.id));
for(const rule of input.rules){
 assert(rule.id&&rule.reason.zh&&rule.reason.en&&rule.display.zh&&rule.display.en);assert(rule.targets.length);assert(rule.sourceIds.length);
 for(const id of rule.sourceIds)assert(sourceIds.has(id),`Missing source ${id}`);
 for(const t of rule.targets){
  assert(!seen.has(t.id),`Duplicate override ${t.id}`);seen.add(t.id);
  assert(Number.isInteger(t.start)&&Number.isInteger(t.end)&&t.start<=t.end);
  for(const records of catalogs)for(const key of ['id','name','start','end','type'])assert.equal(records.get(t.id)?.[key],t[key],`${t.id} ${key} changed`);
 }
}
const data={schemaVersion:1,sources:Object.fromEntries(input.sources.map(s=>[s.id,Object.fromEntries(['id','publisher','title','url','readOn','locator'].map(k=>[k,s[k]]))])),rules:input.rules};
const output='// Generated by scripts/build-polity-display-names.mjs; do not edit.\nexport const polityDisplayData='+JSON.stringify(data)+';\n';
const dest=path.join(root,'public/polity-display-names-data.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(dest,'utf8'),output,'Name display data needs rebuilding');else fs.writeFileSync(dest,output);
console.log(JSON.stringify({ok:true,rules:input.rules.length,records:seen.size,check:process.argv.includes('--check')}));
