"""Extract only ResearchArea, retaining source bytes and every projected vertex.
Usage: python build.py /path/to/downloaded/source/components
Fiona performs inverse Albers projection on the source ellipsoid; no datum shift.
"""
import sys, pathlib, json, gzip, hashlib, zipfile
import fiona
from fiona.transform import transform_geom
ROOT=pathlib.Path(__file__).resolve().parents[2]
source=pathlib.Path(sys.argv[1]);out=ROOT/'public/data/china-prefectures';out.mkdir(parents=True,exist_ok=True)
digest=lambda b:hashlib.sha256(b).hexdigest()
packed=lambda d:json.dumps(d,ensure_ascii=False,separators=(',',':')).encode()
records=[];geometries={};ranges={};files=[];years=[2,742]
with zipfile.ZipFile(out/'ResearchArea-originals.zip','w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
 for p in sorted(source.glob('ResearchArea.*')):
  info=zipfile.ZipInfo(p.name,date_time=(2026,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;z.writestr(info,p.read_bytes())
def coordinates(g):
 for polygon in ([g['coordinates']] if g['type']=='Polygon' else g['coordinates']):
  for ring in polygon:
   yield from ring
with fiona.open(source/'ResearchArea.shp') as data:
 crs=data.crs.to_wkt()
 for row,f in enumerate(data):
  p=dict(f.properties);year=int(p['YEAR'].replace('AD',''));
  if year not in years:continue
  geom=json.loads(packed(dict(transform_geom(data.crs,'+proj=longlat +ellps=krass +no_defs',f.geometry))))
  points=list(coordinates(geom));box=[min(p[0] for p in points),min(p[1] for p in points),max(p[0] for p in points),max(p[1] for p in points)]
  id=f'china-prefecture-{year}-{p["PrefID"]}';assert id not in geometries
  records.append({'id':id,'year':year,'row':row,'bounds':box,'sourceRecord':p});geometries[id]=geom
def save(file,value):
 b=gzip.compress(packed(value),compresslevel=9,mtime=0);(out/file).write_bytes(b)
 files.append({'file':file,'bytes':len(b),'sha256':digest(b)});return files[-1]
metadata={'title':'Zheng & Wu (2026) · ResearchArea historical prefectural units','citation':'Zheng & Wu (2026), Scientific Data, doi:10.1038/s41597-026-07086-6','paper':'https://doi.org/10.1038/s41597-026-07086-6','dataset':'https://doi.org/10.6084/m9.figshare.30518417.v2','download':'https://ndownloader.figshare.com/files/59320670','license':'CC BY 4.0','sourceCRS':crs,'coordinateHandling':'Inverse Albers projection on the original Krassowsky 1940 ellipsoid, without datum shift or coordinate rounding. Source components retained byte-for-byte. Positional precision is limited by the historical reconstruction.','scope':'Exact-year research-area prefectural units. Some units merge prefectures; water surfaces and some frontier areas are excluded. Population Source/RECORDS fields are not boundary citations. SimulatedCountyBoundaries is not used.','years':years,'records':len(records),'sourceRecords':1070,'sourceArchiveSHA256':digest((out/'ResearchArea-originals.zip').read_bytes())}
for stale in out.glob('year-*.json.gz'):stale.unlink()
save('index.json.gz',{'schemaVersion':1,'metadata':metadata,'records':records})
for year in years:
 rows=[r for r in records if r['year']==year];ranges[year]=[min(r['bounds'][0] for r in rows),min(r['bounds'][1] for r in rows),max(r['bounds'][2] for r in rows),max(r['bounds'][3] for r in rows)]
 for band in range(70,151,10):
  selected=[r for r in rows if r['bounds'][0]<=band+20 and r['bounds'][2]>=band-10]
  if selected:save(f'year-{year}-band-{band}.json.gz',{'schemaVersion':1,'year':year,'band':band,'geometries':{r['id']:geometries[r['id']] for r in selected}})
manifest={**metadata,'boundsByYear':ranges,'files':files,'totalBytes':sum(f['bytes'] for f in files)}
(out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
(ROOT/'public/china-prefecture-catalog.js').write_text('// Generated by scripts/china-prefectures/build.py\nexport const chinaPrefectureBounds='+json.dumps(ranges,separators=(',',':'))+';\n')
print(json.dumps({'records':len(records),'files':len(files),'bytes':manifest['totalBytes'],'bounds':ranges,'largestBandBytes':max(f['bytes'] for f in files)}))
